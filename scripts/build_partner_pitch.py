def price_line():
    """Шкала цены: минимум 20 000, рекомендованная 35 000, дальше без потолка. Доля партнёра растёт."""
    H = 118; d = Drawing(W, H)
    x0, x1 = 30, W - 40
    L = x1 - x0
    y_min, y_rec = x0 + L * 0.16, x0 + L * 0.52
    base, bh = 52, 18
    d.add(Rect(x0, base, y_min - x0, bh, fillColor=ZEBRA, strokeColor=None))
    d.add(Rect(y_min, base, y_rec - y_min, bh, fillColor=GOLD_L, strokeColor=None))
    d.add(Rect(y_rec, base, x1 - y_rec, bh, fillColor=GOLD, strokeColor=None))
    d.add(Polygon([x1, base, x1, base + bh, x1 + 12, base + bh / 2], fillColor=GOLD, strokeColor=None))

    d.add(String((x0 + y_min) / 2, base + 6, "нельзя", fontName="DV", fontSize=6.4, fillColor=GREY_T, textAnchor="middle"))
    d.add(String((y_min + y_rec) / 2, base + 6, "обычный коридор", fontName="DV-B", fontSize=7, fillColor=INK, textAnchor="middle"))
    d.add(String((y_rec + x1) / 2, base + 6, "выше рекомендованной — можно", fontName="DV-B", fontSize=7, fillColor=INK, textAnchor="middle"))

    for xx, name, sub in [(y_min, "20 000 ₽", "минимальная цена"), (y_rec, "35 000 ₽", "рекомендованная")]:
        d.add(Line(xx, base - 8, xx, base + bh + 8, strokeColor=INK, strokeWidth=0.9))
        d.add(String(xx, base + bh + 12, name, fontName="DV-B", fontSize=9.5, fillColor=INK, textAnchor="middle"))
        d.add(String(xx, base - 19, sub, fontName="DV", fontSize=6.5, fillColor=GREY_T, textAnchor="middle"))

    d.add(String(x1 + 2, base + bh + 12, "выше", fontName="DV-B", fontSize=9.5, fillColor=GOLD_D, textAnchor="end"))
    d.add(String(x1 + 2, base - 19, "потолка нет", fontName="DV", fontSize=6.5, fillColor=GREY_T, textAnchor="end"))

    for xx, val in [(y_min, 20000), (y_rec, 35000)]:
        d.add(String(xx, base + bh + 26, "вам " + money(val * SHARE), fontName="DV-B", fontSize=8, fillColor=GOLD_D, textAnchor="middle"))
    d.add(String(x1 + 2, base + bh + 26, "вам 35 % от любой цены", fontName="DV-B", fontSize=8, fillColor=GOLD_D, textAnchor="end"))

    d.add(String(x0, 6, "Цену для своей семьи назначаете вы. Ниже минимальной система предложение не создаст.",
                 fontName="DV", fontSize=6.6, fillColor=GREY_T))
    return d


