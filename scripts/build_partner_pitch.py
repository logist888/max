def _chrome(c, doc, bg, fg, mut):
    c.saveState(); c.setFillColor(bg); c.rect(0, 0, PW, PH, stroke=0, fill=1)
    c.setFont("DV-B", 7.2); c.setFillColor(fg); c.drawString(ML, PH - 22, "MAINEXPERTS")
