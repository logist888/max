class Dm(yaml.SafeDumper):
    pass


def _rep(d, data):
    flow = all(not isinstance(v, (dict, list)) for v in data.values()) and sum(len(str(v)) for v in data.values()) < 150 and "text" not in data and "label" not in data
    return d.represent_mapping("tag:yaml.org,2002:map", data.items(), flow_style=flow)


Dm.add_representer(dict, _rep)


