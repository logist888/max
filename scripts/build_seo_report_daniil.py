def scenario_page(n, label, title, lead, rows, tot, note=''):
    g1 = [r for r in rows if num(r[3]) > 0]
    g2 = [r for r in rows if num(r[3]) == 0 and num(r[4]) > 0]
    g3 = [r for r in rows if num(r[3]) == 0 and num(r[4]) == 0]
    body, cls = [], {}
    def grp(lbl, rs, rc):
        if not rs: return
        body.append([lbl]); cls[len(body) - 1] = 'grp'
        for r in rs:
            body.append([r[0], r[1]] + r[2:8]); cls[len(body) - 1] = rc
    grp('Идут в индекс сейчас (K1 > 0)', g1, 'idx')
    grp('Не идут в индекс сейчас, но могут после доработки (K2 > 0)', g2, 'idx2')
    grp('Остальные типы (нет K1 и K2)', g3, '')
    tbl = B.table_html(['Тип', 'Страница'] + COLS, body, cls_rows=cls, tot=['Итого по таблице'] + tot, dense=True)
    ch = sum(tot[1:])
    sumbar = (f'<div class="sumbar"><b>Сумма итого:</b> K1 + K2 + K3 + K4 + K5 = {fmt(tot[1])} + {fmt(tot[2])} + {fmt(tot[3])} + {fmt(tot[4])} + {fmt(tot[5])} = <b>{fmt(ch)}</b>. '
              f'Возможных: <b>{fmt(tot[0])}</b>. ' + ('Сходится.' if ch == tot[0] else f'Расхождение {fmt(abs(ch - tot[0]))}.') + note + '</div>')
    leg = (f'<div class="legend"><span><i style="background:{S["hi"]}"></i>идёт в индекс (K1 &gt; 0)</span><span><i style="background:{S["hi2"]}"></i>может пойти после доработки (K2 &gt; 0)</span>'
           f'<span><i style="background:#fff;border:.2mm solid {S["line"]}"></i>остальные</span></div>')
    add(n, title, f'<h1>{E(title)}</h1><p class="lead">{lead}</p>{leg}{B.fit(tbl)}{sumbar}', label=label)

